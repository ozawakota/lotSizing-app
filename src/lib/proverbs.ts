const DAY_MS = 86_400_000;
const JST_MS = 9 * 60 * 60 * 1000;

/** JST の暦日の通し番号（1970-01-01 JST = 0）。 */
export function jstDayNumber(date: Date): number {
  return Math.floor((date.getTime() + JST_MS) / DAY_MS);
}

const gcd = (a: number, b: number): number => (b === 0 ? a : gcd(b, a % b));

/** n と互いに素な歩幅（n の 2/5 付近から探す。巡回の並びを日ごとにばらけさせるため）。 */
function strideFor(n: number): number {
  if (n <= 2) return 1;
  for (let s = Math.max(2, Math.round(n * 0.4)); s < n; s++) if (gcd(s, n) === 1) return s;
  return 1;
}

/** その日（JST）の格言の番号。同じ日は同じ番号、n 日間は重複しない。 */
export function dailyProverbIndex(date: Date, n: number = PROVERBS.length): number {
  if (n <= 0) return 0;
  const day = jstDayNumber(date);
  return ((((day * strideFor(n)) % n) + n) % n);
}

/** その日（JST）の格言。 */
export function dailyProverb(date: Date = new Date(), list: Proverb[] = PROVERBS): Proverb {
  return list[dailyProverbIndex(date, list.length)];
}
